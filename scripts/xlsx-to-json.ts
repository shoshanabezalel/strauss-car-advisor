/**
 * One-off converter: data/raw/challenge-data.xlsx → data/catalog.json, data/occupations.json,
 * data/sample-employees.json. Output is validated with the same Zod schemas the app uses.
 * Anything that cannot be mapped unambiguously fails the script — no guessing.
 *
 * Usage: npm run data:convert
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import ExcelJS from "exceljs";
import { getChallengeScript } from "../src/lib/config/challenge-script";
import { parseWith } from "../src/lib/config/parse";
import {
  CatalogSchema,
  DRIVES,
  OccupationsSchema,
  RulesSchema,
  SampleEmployeesSchema,
  type Car,
  type Occupation,
  type SampleEmployee,
  type Situation,
} from "../src/lib/config/schemas";
import { validateConfig } from "../src/lib/config/validate";

const ROOT = path.resolve(__dirname, "..");
const XLSX = path.join(ROOT, "data/raw/challenge-data.xlsx");
const SOURCE = "Generated by scripts/xlsx-to-json.ts from data/raw/challenge-data.xlsx — do not edit by hand";

// Sheet names and column headers exactly as they appear in the source workbook.
const SHEETS = {
  catalog: "קטלוג רכבים",
  occupations: "עיסוקים",
  employees: "עובדים לדוגמה",
  calculations: "חישובים",
};
const YES = "כן";
const NO = "לא";
const VEHICLE_TYPE_CODE_PRIVATE = "1"; // TECH-DESIGN §1: catalog cars are private cars

type Row = Record<string, string | number>;

function fail(msg: string): never {
  throw new Error(`xlsx-to-json: ${msg}`);
}

function cellValue(v: ExcelJS.CellValue): string | number {
  if (v === null || v === undefined) return "";
  if (typeof v === "number" || typeof v === "string") return typeof v === "string" ? v.trim() : v;
  if (typeof v === "object" && "richText" in v) return v.richText.map((t) => t.text).join("").trim();
  if (typeof v === "object" && "result" in v) return cellValue(v.result as ExcelJS.CellValue);
  if (typeof v === "boolean") return v ? YES : NO;
  return fail(`unsupported cell value ${JSON.stringify(v)}`);
}

function readSheet(wb: ExcelJS.Workbook, name: string): Row[] {
  const ws = wb.getWorksheet(name) ?? fail(`sheet "${name}" not found`);
  const rows: Row[] = [];
  let headers: string[] = [];
  ws.eachRow((row, i) => {
    const values = (row.values as ExcelJS.CellValue[]).slice(1).map(cellValue);
    if (i === 1) headers = values.map(String);
    else rows.push(Object.fromEntries(headers.map((h, j) => [h, values[j] ?? ""])));
  });
  return rows;
}

const str = (r: Row, col: string): string => {
  const v = r[col];
  if (v === undefined || v === "") fail(`missing value in column "${col}": ${JSON.stringify(r)}`);
  return String(v);
};
const num = (r: Row, col: string): number => {
  const v = r[col];
  const n = typeof v === "number" ? v : Number(String(v).replace(/,/g, ""));
  if (v === "" || !Number.isFinite(n)) fail(`not a number in column "${col}": ${JSON.stringify(v)}`);
  return n;
};
const bool = (r: Row, col: string): boolean => {
  const v = str(r, col);
  if (v === YES) return true;
  if (v === NO) return false;
  return fail(`expected ${YES}/${NO} in column "${col}", got "${v}"`);
};
const pct = (r: Row, col: string): number => Number((num(r, col) / 100).toFixed(10));
const amountIn = (text: string): number | undefined => {
  const m = text.replace(/,/g, "").match(/(\d+)\s*₪/);
  return m ? Number(m[1]) : undefined;
};

async function main() {
  const rules = parseWith(RulesSchema, JSON.parse(readFileSync(path.join(ROOT, "data/strauss-rules.json"), "utf8")), "rules");
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(XLSX);

  // Hebrew drive label → drive enum, through the code mapping in rules.valueOfUse.driveField.
  const driveByLabel = new Map(Object.entries(rules.valueOfUse.driveField).map(([code, label]) => [label, DRIVES[Number(code)]]));

  const cars: Car[] = readSheet(wb, SHEETS.catalog).map((r) => {
    const label = str(r, "הנעה");
    return {
      id: str(r, "מזהה"),
      group: str(r, "קבוצה"),
      make: str(r, "תוצר"),
      makeCode: str(r, "קוד תוצר"),
      model: str(r, "דגם (כינוי מסחרי)"),
      modelCode: str(r, "קוד דגם"),
      modelDescription: str(r, "תאור דגם"),
      vehicleTypeCode: VEHICLE_TYPE_CODE_PRIVATE,
      regYear: num(r, "שנת רישום"),
      drive: driveByLabel.get(label) ?? fail(`unknown drive label "${label}"`),
      listPrice: num(r, "מחיר מחירון"),
      valueOfUse: num(r, "שווי שימוש חודשי"),
      monthlyCost: num(r, "עלות חודשית לחברה (דמה)"),
      defaultParticipation: num(r, "השתתפות עובד ברירת מחדל (דמה)"),
    };
  });

  const occupations: Occupation[] = readSheet(wb, SHEETS.occupations).map((r) => ({
    name: str(r, "עיסוק"),
    group: str(r, "קבוצת זכאות"),
    carMandatory: bool(r, "רכב חובה"),
    waiverAllowed: bool(r, "מותר לוותר"),
    maintenance: num(r, "אחזקת רכב בוויתור (₪)"),
  }));
  const occByName = new Map(occupations.map((o) => [o.name, o]));

  /** Map a free-text car cell ("COROLLA CROSS" / "ATTO 3 (2025)" / waiver text) to a Situation. */
  function toSituation(text: string, participation: number | "catalog_default", occupation: Occupation, who: string): Situation {
    const m = text.match(/^(.*?)\s*\((\d{4})\)$/);
    const model = (m ? m[1] : text).trim();
    const year = m ? Number(m[2]) : undefined;
    const matches = cars.filter((c) => c.model === model && (year === undefined || c.regYear === year));
    if (matches.length > 1) fail(`${who}: "${text}" matches several cars (${matches.map((c) => c.id).join(", ")})`);
    if (matches.length === 1) {
      const car = matches[0];
      return { kind: "car", carId: car.id, participation: participation === "catalog_default" ? car.defaultParticipation : participation };
    }
    const amount = amountIn(text);
    if (amount === undefined) fail(`${who}: cannot map "${text}" to a catalog car or a waiver`);
    if (amount !== occupation.maintenance) {
      fail(`${who}: waiver amount ${amount} in "${text}" differs from occupation maintenance ${occupation.maintenance}`);
    }
    return { kind: "waiver" };
  }

  const calcById = new Map(readSheet(wb, SHEETS.calculations).map((r) => [str(r, "מזהה"), r]));

  const employees: SampleEmployee[] = readSheet(wb, SHEETS.employees).map((r) => {
    const id = str(r, "מזהה");
    const occupation = occByName.get(str(r, "עיסוק")) ?? fail(`${id}: unknown occupation "${r["עיסוק"]}"`);
    const calc = calcById.get(id) ?? fail(`${id}: no row in sheet "${SHEETS.calculations}"`);
    const current = toSituation(str(r, "רכב היום"), num(r, "השתתפות היום"), occupation, `${id} current`);
    if (current.kind === "waiver" && num(r, "השתתפות היום") !== 0) fail(`${id}: waiver with non-zero participation`);
    const alternative = toSituation(str(calc, "החלופה"), "catalog_default", occupation, `${id} alternative`);
    return {
      id,
      name: str(r, "שם"),
      nationalId: str(r, "ת״ז (פיקטיבית)"),
      question: str(r, "השאלה"),
      profile: {
        occupation: occupation.name,
        group: str(r, "קבוצה"),
        baseSalary: num(r, "שכר בסיס"),
        commissions: num(r, "עמלות"),
        bonus: num(r, "בונוס"),
        pensionPct: pct(r, "פנסיה עובד %"),
        studyFundPct: pct(r, "קרן השתלמות עובד %"),
        creditPoints: num(r, "נקודות זיכוי"),
        childrenUnder23: num(r, "ילדים עד 23"),
        current,
      },
      alternative,
      ...(alternative.kind === "car" ? { alternativeParticipationSource: "catalog_default (reference data)" as const } : {}),
      expected: {
        eligible: bool(calc, "זכאות"),
        reason: str(calc, "סיבה"),
        netToday: num(calc, "נטו היום"),
        netAlt: num(calc, "נטו בחלופה"),
        diff: num(calc, "הפרש"),
        taxToday: num(calc, "מס היום"),
        taxAlt: num(calc, "מס בחלופה"),
        niHealthToday: num(calc, "ביטוח לאומי+בריאות היום"),
        niHealthAlt: num(calc, "ביטוח לאומי+בריאות בחלופה"),
        electricGross: num(calc, "החזר חשמל ברוטו"),
        familyGapEmployee: num(calc, "חלק העובד במסלול המשפחתי"),
        why: str(calc, "למה"),
      },
    };
  });

  const catalog = parseWith(CatalogSchema, { source: SOURCE, cars }, "catalog");
  const occ = parseWith(OccupationsSchema, { source: SOURCE, occupations }, "occupations");
  const emp = parseWith(SampleEmployeesSchema, { source: SOURCE, employees }, "sample-employees");
  // The challenge script is hand-written (not in the xlsx); validated against the new catalog too.
  validateConfig({ rules, catalog, occupations: occ, employees: emp, challenge: getChallengeScript() });

  const write = (file: string, data: unknown) => {
    writeFileSync(path.join(ROOT, "data", file), JSON.stringify(data, null, 2) + "\n", "utf8");
    console.log(`wrote data/${file}`);
  };
  write("catalog.json", catalog);
  write("occupations.json", occ);
  write("sample-employees.json", emp);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
